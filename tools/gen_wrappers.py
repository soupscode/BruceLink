#!/usr/bin/env python3
"""Generate one-line wrapper sources that pull the shared protocol core (and,
for the ESP32 compile check, the bridge library) into each device build.

Why: both devices must compile the SAME core sources. Symlinks did that but
break on Windows checkouts, so each build tree instead holds tiny wrapper
files that #include the real source by relative path. One wrapper per source
keeps every file its own translation unit (the core has same-named static
helpers in different files).

    python3 tools/gen_wrappers.py           # (re)generate
    python3 tools/gen_wrappers.py --check   # exit 1 if anything is stale

Run it after adding, removing or renaming a file in shared/brucelink_core/src
or esp32/lib/BruceLink. tests/test_wrappers.py runs --check in CI.
SPDX-License-Identifier: MIT
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "shared" / "brucelink_core" / "src"
BRIDGE = ROOT / "esp32" / "lib" / "BruceLink"
HEADER = "/* GENERATED by tools/gen_wrappers.py - do not edit. */\n"

# (output dir, source dir, glob)
TARGETS = [
    (ROOT / "flipper" / "brucelink" / "core", CORE, "*.c"),
    (ROOT / "esp32" / "test_compile" / "src" / "core", CORE, "*.c"),
    (ROOT / "esp32" / "test_compile" / "src" / "bridge", BRIDGE, "*.cpp"),
]


def expected():
    out = {}
    for out_dir, src_dir, pattern in TARGETS:
        for src in sorted(src_dir.glob(pattern)):
            rel = Path(os.path.relpath(src, out_dir)).as_posix()
            out[out_dir / src.name] = f'{HEADER}#include "{rel}"\n'
    return out


def main():
    check = "--check" in sys.argv
    want = expected()
    stale = [p for p, text in want.items() if not p.exists() or p.read_text() != text]
    extra = [
        p
        for out_dir, _, _ in TARGETS
        if out_dir.exists()
        for p in out_dir.iterdir()
        if p not in want
    ]
    if check:
        for p in stale:
            print(f"stale or missing: {p.relative_to(ROOT)}")
        for p in extra:
            print(f"unexpected:       {p.relative_to(ROOT)}")
        return 1 if (stale or extra) else 0
    for p in extra:
        p.unlink()
    for p, text in want.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    print(f"{len(want)} wrappers up to date ({len(stale)} written, {len(extra)} removed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
